#!/usr/bin/env python3
"""Generate src/kernels/quant_grids.h: IQ1_S (also IQ1_M) / IQ2_XXS / IQ2_XS grid table VALUES (data, from the public ggml format
description ggml-common.h) plus derived GPU-friendly tables. Usage: gen_quant_grids.py path/to/ggml-common.h out.h"""
import re, sys

src = open(sys.argv[1]).read()

def table(name):
    m = re.search(r'GGML_TABLE_BEGIN\(\w+,\s*' + name + r',\s*\w+\)(.*?)GGML_TABLE_END', src, re.S)
    return [int(v, 0) for v in re.findall(r'-?0x[0-9a-fA-F]+|-?\d+', m.group(1))]

iq1s = table('iq1s_grid'); assert len(iq1s) == 2048
iq2xxs = table('iq2xxs_grid'); assert len(iq2xxs) == 256
iq2xs = table('iq2xs_grid'); assert len(iq2xs) == 512
ksigns = table('ksigns_iq2xs'); assert len(ksigns) == 128
# derived: byte mask (0xFF where the sign bit is set) for each 7-bit sign index (parity bit included by ksigns)
signmask = []
for s in ksigns:
    m = 0
    for j in range(8):
        if s & (1 << j): m |= 0xFF << (8 * j)
    signmask.append(m)

def fmt(vals, w):
    out = []
    for i in range(0, len(vals), 8):
        out.append(', '.join(('0x%0' + str(w) + 'x') % v for v in vals[i:i + 8]))
    return ', \\\n  '.join(out)

with open(sys.argv[2], 'w') as f:
    f.write('// GENERATED by tools/gen_quant_grids.py -- do not edit. Grid VALUES from the public ggml format tables.\n')
    f.write('// Shared by Metal (src/kernels) and the CPU reference (tests/ref). Each macro is a comma list.\n#pragma once\n\n')
    f.write('// IQ1_S: 2048 entries, 8 x int8 in {-1,0,1} per entry (byte j = element j)\n')
    f.write('#define Q_IQ1S_GRID_VALUES \\\n  ' + fmt(iq1s, 16) + '\n\n')
    f.write('// IQ2_XXS: 256 entries, 8 x uint8 in {8,25,43} per entry\n')
    f.write('#define Q_IQ2XXS_GRID_VALUES \\\n  ' + fmt(iq2xxs, 16) + '\n\n')
    f.write('// IQ2_XS: 512 entries, 8 x uint8 in {8,25,43} per entry\n')
    f.write('#define Q_IQ2XS_GRID_VALUES \\\n  ' + fmt(iq2xs, 16) + '\n\n')
    f.write('// ksigns_iq2xs: 7-bit index -> 8 sign bits (bit 7 = parity)\n')
    f.write('#define Q_KSIGNS_IQ2XS_VALUES \\\n  ' + fmt(ksigns, 2) + '\n\n')
    f.write('// derived: 7-bit sign index -> 8 byte masks (0xFF = negate element j)\n')
    f.write('#define Q_IQ2_SIGNMASK_VALUES \\\n  ' + fmt(signmask, 16) + '\n')
    # derived: IQ1_S grid as 8 halfs per entry (4 x uint32, little endian: element 2i in the low half of word i)
    H = {0xff: 0xBC00, 0x00: 0x0000, 0x01: 0x3C00}
    words = []
    for v in iq1s:
        b = [(v >> (8 * j)) & 0xff for j in range(8)]
        for i in range(4): words.append(H[b[2 * i]] | (H[b[2 * i + 1]] << 16))
    f.write('\n// derived: IQ1_S grid as half values, 4 x uint32 (= 8 halfs) per entry\n')
    f.write('#define Q_IQ1S_GRID_HALF_VALUES \\\n  ' + fmt(words, 8) + '\n')
    import struct as _st
    def h(v): return _st.unpack('<H', _st.pack('<e', float(v)))[0]
    words = []
    for v in iq2xxs:
        b = [(v >> (8 * j)) & 0xff for j in range(8)]
        for i in range(4): words.append(h(b[2 * i]) | (h(b[2 * i + 1]) << 16))
    f.write('\n// derived: IQ2_XXS grid as half values, 4 x uint32 per entry\n')
    f.write('#define Q_IQ2XXS_GRID_HALF_VALUES \\\n  ' + fmt(words, 8) + '\n')
    words = []
    for v in iq2xs:
        b = [(v >> (8 * j)) & 0xff for j in range(8)]
        for i in range(4): words.append(h(b[2 * i]) | (h(b[2 * i + 1]) << 16))
    f.write('\n// derived: IQ2_XS grid as half values, 4 x uint32 per entry\n')
    f.write('#define Q_IQ2XS_GRID_HALF_VALUES \\\n  ' + fmt(words, 8) + '\n')
    words = []
    for sg in ksigns:
        for i in range(4):
            w = (0x8000 if sg & (1 << (2 * i)) else 0) | (0x80000000 if sg & (1 << (2 * i + 1)) else 0)
            words.append(w)
    f.write('\n// derived: 7-bit sign index -> half sign-bit masks (4 x uint32 = 8 halfs)\n')
    f.write('#define Q_IQ2_SIGNH_VALUES \\\n  ' + fmt(words, 8) + '\n')
print('ok')
