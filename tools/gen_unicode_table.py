#!/usr/bin/env python3
"""Generate src/tok/unicode_table.inc: a compact two-stage codepoint -> class table for the tokenizer.

Data source: Python's own `unicodedata` module (stdlib, Unicode version printed into the header).
Classes (uint8):
    0 = other (C*, Z* that is not White_Space, unassigned)
    1 = number (N*)   2 = letter (L*)   3 = punctuation (P*)   4 = mark (M*)   5 = symbol (S*)
    6 = whitespace (Unicode White_Space property; takes precedence over the category)
Layout: stage1[cp >> 8] -> block index (uint16), stage2[block * 256 + (cp & 255)] -> class.
Usage: python3 tools/gen_unicode_table.py [--unicode16] > src/tok/unicode_table.inc

Compatibility: the oracle (llama.cpp unicode-data.cpp, used by llama-tokenize) is generated from Unicode 15.1.
By default codepoints first assigned in Unicode 16.0 are therefore treated as unassigned (class 0), which makes
the pre-tokenizer bit-identical to the oracle. Pass --unicode16 to keep them (then 5185 rare codepoints differ).
"""
import sys
import unicodedata

# Unicode White_Space property (PropList.txt); stable since Unicode 6.3.
WHITE_SPACE = set(list(range(0x09, 0x0E)) + [0x20, 0x85, 0xA0, 0x1680] + list(range(0x2000, 0x200B)) +
                  [0x2028, 0x2029, 0x202F, 0x205F, 0x3000])
CAT = {'N': 1, 'L': 2, 'P': 3, 'M': 4, 'S': 5}
MAXCP = 0x110000

# DerivedAge.txt (Unicode 16.0.0): ranges with Age=16.0
AGE_16_0 = """0897 1B4E..1B4F 1B7F 1C89..1C8A 2427..2429 31E4..31E5 A7CB..A7CD A7DA..A7DC 105C0..105F3 10D40..10D65
10D69..10D85 10D8E..10D8F 10EC2..10EC4 10EFC 11380..11389 1138B 1138E 11390..113B5 113B7..113C0 113C2 113C5
113C7..113CA 113CC..113D5 113D7..113D8 113E1..113E2 116D0..116E3 11BC0..11BE1 11BF0..11BF9 11F5A 13460..143FA
16100..16139 16D40..16D79 18CFF 1CC00..1CCF9 1CD00..1CEB3 1E5D0..1E5FA 1E5FF 1F8B2..1F8BB 1F8C0..1F8C1 1FA89 1FA8F
1FABE 1FAC6 1FADC 1FADF 1FAE9 1FBCB..1FBEF"""
MASKED = set()


def _parse_age():
    for r in AGE_16_0.split():
        a, b = (r.split("..") + [r])[:2]
        MASKED.update(range(int(a, 16), int(b, 16) + 1))


def cls(cp):
    if cp in WHITE_SPACE:
        return 6
    if cp in MASKED:
        return 0
    return CAT.get(unicodedata.category(chr(cp))[0], 0)


def main():
    if "--unicode16" not in sys.argv:
        if not unicodedata.unidata_version.startswith(("15.1", "16.0")):
            sys.stderr.write("warning: unicodedata %s: only 16.0 additions are masked\n" % unicodedata.unidata_version)
        _parse_age()
    blocks, index, stage1 = [], {}, []
    for hi in range(MAXCP >> 8):
        blk = bytes(cls((hi << 8) | lo) for lo in range(256))
        if blk not in index:
            index[blk] = len(blocks)
            blocks.append(blk)
        stage1.append(index[blk])
    out = sys.stdout
    out.write("// generated by tools/gen_unicode_table.py from Python unicodedata %s -- do not edit\n" %
              unicodedata.unidata_version)
    out.write("// %s\n" % ("Unicode 16.0 additions masked as unassigned (llama.cpp / Unicode 15.1 compatible)"
                            if MASKED else "no masking"))
    out.write("// classes: 0 other, 1 N, 2 L, 3 P, 4 M, 5 S, 6 White_Space\n")
    out.write("static const char kUnicodeVersion[] = \"%s\";\n" % unicodedata.unidata_version)
    out.write("static const uint16_t kUcStage1[%d] = {\n" % len(stage1))
    for i in range(0, len(stage1), 24):
        out.write(",".join(str(v) for v in stage1[i:i + 24]) + ",\n")
    out.write("};\n")
    out.write("static const uint8_t kUcStage2[%d] = {\n" % (len(blocks) * 256))
    for b in blocks:
        for i in range(0, 256, 64):
            out.write(",".join(str(v) for v in b[i:i + 64]) + ",\n")
    out.write("};\n")
    sys.stderr.write("unicode %s: %d unique blocks, %d bytes\n" %
                     (unicodedata.unidata_version, len(blocks), len(blocks) * 256 + len(stage1) * 2))


if __name__ == "__main__":
    main()
